def objects_mdx(
    ctx: Context,
    title: str,
    roots: Sequence[type],
    models: Sequence[type],
    enums: Sequence[NamedEnum],
    defs: Dict[str, Dict[str, Any]],
    pills: Dict[type, Dict[str, List[Tuple[str, str]]]],
) -> str:
    """One category's objects and enums, as anchored tables under a tree.

    The tables are rendered before anything is emitted, because rendering is
    what discovers which enums the category reaches and which of them are homed
    here. Every named enum in the pack is offered and the filter runs at the
    end: the type modules declare aliases for parts of an API a pack has not
    covered yet, and a section for one of those is a table nothing links to.
    """
    published = set(models)
    body: List[str] = []

    for model in models:
        node = defs.get(f"{model.__name__}{_LLM_SUFFIX}") or defs.get(model.__name__)
        if node is None:
            continue
        body += [f"## {model.__name__}", ""]
        # Split on the first blank line, counting a whitespace-only line as
        # blank. Before 3.13 a docstring kept its source indentation, so the
        # "blank" line between a summary and its API Reference was the file's
        # indent rather than an empty string and this split found nothing to
        # cut on; 3.13 strips that indentation (gh-81283) and the same
        # docstring suddenly has a paragraph break. Matching either way keeps
        # the generated page identical on every supported version.
        doc = _PARAGRAPH_BREAK.split((model.__doc__ or "").strip())[0]
        if doc:
            body += [mdx(doc), ""]
        rows = field_rows(
            ctx, node.get("properties", {}), set(node.get("required", [])), pills.get(model, {})
        )
        body += [table(rows) if rows else "This object has no settable fields.", ""]

    for enum in enums:
        if enum.values not in ctx.used or ctx.enum_homes.get(enum.values) != ctx.category:
            continue
        values = [f"| {code(value)} |" for value in enum.values]
        body += [
            f"## {enum.name}",
            "",
            wrapped("enum-table", ["| Value |", "| --- |", *values]),
            "",
        ]

    if not body:
        return ""

    head = [
        "---",
        'title: "Objects"',
        f'description: "Every object and enum the {title} tools accept."',
        "---",
        "",
        _BANNER,
        "",
    ]
    if roots:
        head += ["## Model tree", "", tree_html(ctx, roots, published), ""]

    return "\n".join(head + body).rstrip() + "\n"


