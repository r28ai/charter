def _pack_title(pack: str) -> str:
    """The pack's display name, read off its overview page's frontmatter."""
    text = (PACK_DOCS / f"{pack}.mdx").read_text()
    match = re.search(r'^title:\s*"(.+?)"', text, re.MULTILINE)
    return match.group(1) if match else pack


def pack_nav(pack: str) -> Dict[str, Any]:
    module = pack_module(pack)
    tools = list(module.TOOLS)
    groups = categorised(pack, tools)

    pages: List[Any] = [f"packs/{pack}"]
    published = pack_pages(pack)
    for slug, category_tools in groups:
        directory = f"packs/{pack}/{slug}" if slug else f"packs/{pack}"
        leaves = [f"{directory}/{tool.name}" for tool in category_tools]
        if f"{directory}/objects.mdx" in published:
            leaves.append(f"{directory}/objects")
        if slug is None:
            pages.extend(leaves)
        else:
            pages.append({"group": category_title(pack, slug), "pages": leaves})

    return {"group": _pack_title(pack), "expanded": False, "pages": pages}


def packs_tab() -> Dict[str, Any]:
    oauth, api_key = [], []
    for pack in PACKS:
        tools = list(pack_module(pack).TOOLS)
        target = oauth if tools[0].credential_provider is not None else api_key
        target.append(pack_nav(pack))
    return {
        "tab": "Packs",
        "pages": [
            "packs/overview",
            {"group": "OAuth packs", "pages": oauth},
            {"group": "API-key packs", "pages": api_key},
        ],
    }


# Where every tool page lived while the pack reference was one OpenAPI document
# per pack: ``packs/<pack>/tools/<tool>``, from the tag on every operation.
_LEGACY_SEGMENT = "tools"


def tool_redirects() -> List[Dict[str, str]]:
    """From the tag-derived path each tool page used to have, to where it is now.

    These pages are what the pack pages have linked to since the packs shipped,
    and a reader who bookmarked one should not meet a 404 because the reference
    changed how it groups things.
    """
    out = []
    for pack in PACKS:
        for tool in pack_module(pack).TOOLS:
            source = f"/packs/{pack}/{_LEGACY_SEGMENT}/{tool.name}"
            destination = tool_page_path(pack, tool)
            if source != destination:
                out.append({"source": source, "destination": destination})
    return out


def render_docs_json() -> str:
    config = json.loads((DOCS / "docs.json").read_text())
    tabs = config["navigation"]["tabs"]
    for index, tab in enumerate(tabs):
        if tab["tab"] == "Packs":
            tabs[index] = packs_tab()
            break

    # ``api`` configured Mintlify's OpenAPI renderer — a hidden playground,
    # collapsed nested params, and which ``x-charter-*`` keys became pills. No
    # pack ships an OpenAPI document any more, so all of it is inert.
    config.pop("api", None)

    kept = [
        redirect
        for redirect in config.get("redirects", [])
        if f"/{_LEGACY_SEGMENT}/" not in redirect["source"]
    ]
    config["redirects"] = kept + tool_redirects()
    return json.dumps(config, indent=2) + "\n"


