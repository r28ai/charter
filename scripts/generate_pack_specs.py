# The suffix ``create_llm_schema`` gives a model it derives. A def named
# ``Event_LLM`` is the LLM's view of the wire model ``Event``, and that is how a
# marker declared on the wire finds the property it belongs to.
_LLM_SUFFIX = "_LLM"

# An unnamed inline enum wider than this is not a type a reader can hold in a
# table cell. Its values move to the description and the cell says `string`.
_INLINE_ENUM_MAX = 4

# A blank line, or one holding only the indentation a docstring was written
# with. See the use site in object_section for why both have to count.
_PARAGRAPH_BREAK = re.compile(r"\n[ \t]*\n")

# -----------------------------------------------------
# MDX escaping
# -----------------------------------------------------

# MDX parses `{` as the start of an expression and `<` as the start of a tag, so
# provider prose — which is full of `{calendarId}` and `<= 250` — has to be
# escaped anywhere it lands outside a code span.
_MDX_ESCAPES = {"{": "&#123;", "}": "&#125;", "<": "&lt;", ">": "&gt;"}


def mdx(text: str) -> str:
    """One-line prose, safe to drop into MDX and into a table cell."""
    text = " ".join(str(text).split())
    for raw, entity in _MDX_ESCAPES.items():
        text = text.replace(raw, entity)
    return text.replace("|", "\\|")


def code(text: str) -> str:
    """A code span. Its contents are never parsed, so nothing is escaped."""
    return f"`{text}`"


def jsx_string(text: str) -> str:
    """A string as a JSX expression, for text that must survive verbatim.

    Entities are not decoded inside a Mintlify ``<code>`` element, so a route
    escaped with ``&#123;`` renders the entity rather than the brace. A string
    literal in an expression is the one form MDX passes through untouched.
    """
    return "{" + json.dumps(str(text)) + "}"


# -----------------------------------------------------
# Packs, categories, and where a model lives
# -----------------------------------------------------


def pack_module(pack: str) -> ModuleType:
    return importlib.import_module(f"charter.packs.{pack}")


def _types_root(pack: str) -> str:
    return f"charter.packs.{pack}.types"


def category_of(model: Any, pack: str) -> Optional[str]:
    """The category slug for anything declared under the pack's ``types``.

    ``charter.packs.gmail.types.message.models`` is ``message``; a model in
    ``types/__init__.py`` has no category, and a pack whose models all land
    there is rendered flat. Takes a class or the module itself, which name the
    module they live in differently.
    """
    root = _types_root(pack)
    module = model.__name__ if isinstance(model, ModuleType) else getattr(model, "__module__", "")
    if not module.startswith(root):
        return None
    rest = module[len(root) :].lstrip(".")
    slug = rest.split(".")[0]
    return slug or None


def category_title(pack: str, slug: str) -> str:
    """The category's display name.

    Derived from the slug, unless the category package names itself. Google
    spells it ``calendarList`` and the module has to be ``calendar_list``, so
    ``__title__`` in the category's ``__init__.py`` settles the difference.
    """
    try:
        module = importlib.import_module(f"{_types_root(pack)}.{slug}")
    except ImportError:
        module = None
    declared = getattr(module, "__title__", None)
    if declared:
        return str(declared)
    words = slug.split("_")
    return " ".join([words[0].capitalize(), *words[1:]])


def categorised(pack: str, tools: Sequence[Tool]) -> List[Tuple[Optional[str], List[Tool]]]:
    """The pack's tools, grouped by the module their request models live in.

    Insertion-ordered, so the sidebar follows the order ``TOOLS`` declares.
    A pack with a single category is returned under ``None`` — one group named
    after the only thing in it is a level that says nothing.
    """
    groups: Dict[Optional[str], List[Tool]] = {}
    for tool in tools:
        groups.setdefault(category_of(tool.args_schema, pack), []).append(tool)
    if len(groups) == 1:
        return [(None, next(iter(groups.values())))]
    return list(groups.items())


# -----------------------------------------------------
# Named enums, recovered from the type modules
# -----------------------------------------------------


@dataclass(frozen=True)
class NamedEnum:
    name: str
    values: Tuple[str, ...]
    category: Optional[str]


def _literal_values(annotation: Any) -> Optional[Tuple[str, ...]]:
    from typing import Literal

    if get_origin(annotation) is Literal:
        args = get_args(annotation)
        if args and all(isinstance(arg, str) for arg in args):
            return tuple(args)
    return None


def named_enums(pack: str) -> Dict[Tuple[str, ...], NamedEnum]:
    """Every module-level ``Literal`` alias in the pack, keyed by its values.

    Two aliases that spell the same values are the same enum as far as a
    schema can tell, so the first one declared wins and both fields link to it.
    """
    found: Dict[Tuple[str, ...], NamedEnum] = {}
    root = importlib.import_module(_types_root(pack))
    modules = [root]
    for info in pkgutil.walk_packages(root.__path__, prefix=f"{_types_root(pack)}."):
        try:
            modules.append(importlib.import_module(info.name))
        except ImportError:
            continue

    for module in modules:
        for name, value in vars(module).items():
            if name.startswith("_"):
                continue
            values = _literal_values(value)
            if values is None or values in found:
                continue
            # Re-exported aliases keep the defining module's category.
            found[values] = NamedEnum(name, values, category_of(module, pack))
    return found


# -----------------------------------------------------
# Walking a model's tree
# -----------------------------------------------------


def _referenced_models(annotation: Any) -> Iterable[type]:
    """Every ``BaseModel`` inside an annotation, however deeply parameterised."""
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        yield annotation
        return
    for arg in get_args(annotation):
        yield from _referenced_models(arg)


def model_tree(model: type, seen: Optional[Set[type]] = None) -> List[type]:
    """``model`` and everything reachable from it, in declaration order."""
    seen = set() if seen is None else seen
    if model in seen:
        return []
    seen.add(model)
    out = [model]
    for field in model.model_fields.values():
        for nested in _referenced_models(field.annotation):
            out.extend(model_tree(nested, seen))
    return out


def direct_children(model: type) -> List[type]:
    """The models one hop from ``model``, deduplicated, in declaration order."""
    out: List[type] = []
    for field in model.model_fields.values():
        for nested in _referenced_models(field.annotation):
            if nested not in out:
                out.append(nested)
    return out


# -----------------------------------------------------
# Markers, as pills
# -----------------------------------------------------


def _pills(field: Any) -> List[Tuple[str, str]]:
    """The markers on one field that are worth showing beside its type.

    ``Path``/``Query``/``Body`` are deliberately absent: the page heads each
    table with where the value lands, so a ``query`` pill under "Query
    parameters" is noise. What is left is the part no other catalogue prints —
    that a value is re-encoded on the way out, that it is accepted but never
    returned, that its key is spelled differently from the rest of the pack.
    """
    modes: Set[str] = set()
    for marker in field.metadata:
        if isinstance(marker, Mode):
            modes |= marker.modes
    if modes & {"response_only", "disabled"}:
        # Dropped from the LLM view before the schema is built. A pill for it
        # would describe a field the caller cannot set.
        return []

    pills: List[Tuple[str, str]] = []
    for marker in field.metadata:
        if isinstance(marker, Format):
            pills.append(("transform", marker.transform))
        elif isinstance(marker, Case):
            pills.append(("case", marker.case))
    for mode in sorted(modes):
        pills.append(("mode", mode))
    return pills


def marker_map(model: type) -> Dict[type, Dict[str, List[Tuple[str, str]]]]:
    """``{wire model: {camelCase property: pills}}`` for a whole tree."""
    out: Dict[type, Dict[str, List[Tuple[str, str]]]] = {}
    for node in model_tree(model):
        here = {to_camel(name): _pills(f) for name, f in node.model_fields.items()}
        out[node] = {name: pills for name, pills in here.items() if pills}
    return out


def render_pills(pills: Sequence[Tuple[str, str]]) -> str:
    if not pills:
        return ""
    spans = "".join(
        f'<span className="marker" data-marker="{kind}">{mdx(value)}</span>' for kind, value in pills
    )
    return f'<br /><span className="markers">{spans}</span>'


# -----------------------------------------------------
# Rendering one type
# -----------------------------------------------------


@dataclass
class Context:
    """What a type needs in order to render itself as a link."""

    pack: str
    category: Optional[str]
    enums: Dict[Tuple[str, ...], NamedEnum]
    # Which category page each enum is published on, filled in at first use and
    # shared across the pack's categories so the second user links to the first.
    enum_homes: Dict[Tuple[str, ...], Optional[str]] = dc_field(default_factory=dict)
    # The objects page currently being rendered, if any. A link is shortened to
    # a bare anchor only when its target is a heading on this very page.
    page: Optional[str] = None
    # LLM def name (``Event_LLM``) -> the wire model it came from.
    models: Dict[str, type] = dc_field(default_factory=dict)
    # Which category page each wire model is published on.
    homes: Dict[type, Optional[str]] = dc_field(default_factory=dict)
    # Named enums some rendered field actually reached, filled in as we go.
    used: Set[Tuple[str, ...]] = dc_field(default_factory=set)


def anchor(name: str) -> str:
    """Mintlify's anchor for a heading, which is the heading slugified.

    An underscore survives the slug; every other run of punctuation becomes a
    hyphen. That asymmetry is load-bearing rather than cosmetic: the shipped
    ``/reference/tool#tool-llm_schema`` is the anchor for ``Tool.llm_schema``,
    so the dot became a hyphen and the underscore did not. No generated heading
    contains one today, which is why folding them was invisible here.
    """
    return re.sub(r"[^a-z0-9_]+", "-", name.lower()).strip("-")


def objects_page(pack: str, category: Optional[str]) -> str:
    return f"packs/{pack}/{category}/objects" if category else f"packs/{pack}/objects"


def tool_page_path(pack: str, tool: Tool) -> str:
    """Where one tool's page is published.

    ``generate_pack_docs.py`` links the pack page's tool list here, and
    ``tests/test_pack_specs.py`` holds the two together.
    """
    category = category_of(tool.args_schema, pack)
    module = pack_module(pack)
    if len(categorised(pack, list(module.TOOLS))) == 1:
        category = None
    return f"/packs/{pack}/{category}/{tool.name}" if category else f"/packs/{pack}/{tool.name}"


def href_to(ctx: Context, name: str, home: Optional[str]) -> str:
    """Where an object or enum section lives, from wherever we are now."""
    page = objects_page(ctx.pack, home)
    fragment = f"#{anchor(name)}"
    return fragment if page == ctx.page else f"/{page}{fragment}"


def link_to(ctx: Context, name: str, home: Optional[str]) -> str:
    """A markdown link to an object or enum section."""
    return f"[{name}]({href_to(ctx, name, home)})"


def link_html(ctx: Context, name: str, home: Optional[str]) -> str:
    """The same link as an anchor, for the tree, where MDX parses no markdown."""
    return f'<a href="{href_to(ctx, name, home)}">{name}</a>'


def _enum_of(node: Dict[str, Any]) -> Optional[List[str]]:
    values = node.get("enum")
    if isinstance(values, list) and all(isinstance(v, str) for v in values):
        return values
    return None


def render_type(ctx: Context, node: Dict[str, Any]) -> Tuple[str, List[str]]:
    """One schema node as a type cell, plus any notes it pushed to the description.

    Returns ``(cell, notes)``. A wide unnamed enum is the only thing that pushes:
    ten string literals do not fit a type column, so the cell says ``string`` and
    the values go to the description.
    """
    notes: List[str] = []

    ref = node.get("$ref")
    if ref:
        def_name = ref.rsplit("/", 1)[1]
        model = ctx.models.get(def_name)
        if model is not None:
            wire = model.__name__
            return link_to(ctx, wire, ctx.homes.get(model)), notes
        return code(def_name.removesuffix(_LLM_SUFFIX)), notes

    if "anyOf" in node:
        # ``Optional[X]`` is the overwhelming case, and "or null" on two thirds
        # of every table is a column of noise. The tables mark what is required;
        # nullability is the complement of that and is not repeated here.
        variants = [v for v in node["anyOf"] if v.get("type") != "null"]
        if len(variants) == 1:
            return render_type(ctx, variants[0])
        cells = []
        for variant in variants:
            cell, extra = render_type(ctx, variant)
            cells.append(cell)
            notes.extend(extra)
        return " \\| ".join(cells), notes

    values = _enum_of(node)
    if values is not None:
        known = ctx.enums.get(tuple(values))
        if known is not None:
            ctx.used.add(known.values)
            home = ctx.enum_homes.setdefault(known.values, ctx.category)
            return link_to(ctx, known.name, home), notes
        if len(values) <= _INLINE_ENUM_MAX:
            return code(" \\| ".join(f'"{v}"' for v in values)), notes
        notes.append("One of " + ", ".join(code(v) for v in values) + ".")
        return code("string"), notes

    kind = node.get("type")
    if kind == "array":
        inner, extra = render_type(ctx, node.get("items", {}))
        notes.extend(extra)
        return f"{inner}[]", notes
    if kind == "object":
        extra_props = node.get("additionalProperties")
        if isinstance(extra_props, dict):
            inner, more = render_type(ctx, extra_props)
            notes.extend(more)
            return f"map of {inner}", notes
        return code("object"), notes
    if kind is None:
        return code("any"), notes
    return code(str(kind)), notes


_CONSTRAINTS = [
    ("minLength", "min length {}"),
    ("maxLength", "max length {}"),
    ("minimum", "≥ {}"),
    ("exclusiveMinimum", "> {}"),
    ("maximum", "≤ {}"),
    ("exclusiveMaximum", "< {}"),
    ("minItems", "min {} items"),
    ("maxItems", "max {} items"),
    ("pattern", "matches `{}`"),
    ("format", "format `{}`"),
]


def constraints_of(node: Dict[str, Any]) -> List[str]:
    """The bounds the provider declared, flattened out of any ``anyOf``."""
    nodes = [node, *[v for v in node.get("anyOf", []) if v.get("type") != "null"]]
    out: List[str] = []
    for candidate in nodes:
        for key, template in _CONSTRAINTS:
            if key in candidate:
                rendered = template.format(candidate[key])
                if rendered not in out:
                    out.append(rendered)
    return out


def describe(node: Dict[str, Any], notes: Sequence[str]) -> str:
    """The description cell: the provider's prose, then what bounds it."""
    parts: List[str] = []
    description = node.get("description")
    if description:
        parts.append(mdx(description))
    parts.extend(notes)

    bounds = constraints_of(node)
    default = node.get("default")
    if default is not None:
        bounds.append(f"defaults to `{json.dumps(default)}`")
    if bounds:
        parts.append(f'<span className="field-constraints">{mdx("; ".join(bounds))}</span>')
    return " ".join(parts) or "—"


# -----------------------------------------------------
# Tables
# -----------------------------------------------------


def field_rows(
    ctx: Context,
    properties: Dict[str, Any],
    required: Set[str],
    pills: Dict[str, List[Tuple[str, str]]],
) -> List[str]:
    rows = []
    for name, node in properties.items():
        cell, notes = render_type(ctx, node)
        flag = (
            ' <span className="required" title="required">*</span>' if name in required else ""
        )
        rows.append(
            f"| {code(name)}{flag} | {cell}{render_pills(pills.get(name, []))} | {describe(node, notes)} |"
        )
    return rows


def table(rows: Sequence[str]) -> str:
    """A field table, wrapped so the stylesheet can find it.

    A markdown table carries no class, and the column widths these tables want
    are not the widths a hand-written table on a pack page wants. The wrapper is
    what separates them; the blank lines are what keep the markdown inside it
    parsed as markdown.
    """
    return wrapped(
        "reference-table",
        ["| Field | Type | Description |", "| --- | --- | --- |", *rows],
    )


def wrapped(class_name: str, lines: Sequence[str]) -> str:
    return "\n".join([f'<div className="{class_name}">', "", *lines, "", "</div>"])


# -----------------------------------------------------
# The model tree
# -----------------------------------------------------


def tree_html(ctx: Context, roots: Sequence[type], published: Set[type]) -> str:
    """The category's models as a tree, links down to the tables below it.

    Each model is drawn once, at its first occurrence, and every later
    appearance is a leaf noted as drawn above. A shape reached from two places
    is the normal case rather than the exception — Google Calendar's
    ``ConferenceSolutionKey`` hangs off both ``ConferenceSolution`` and
    ``CreateRequest`` — and redrawing its subtree at each one makes the tree
    claim more models than the category has.

    Drawn whole. An earlier version stopped at depth two and carried a ``+N``
    of what it had not drawn, which was wrong twice over: the counts
    double-counted a shared model, and nothing was actually hidden, since every
    model in the count has its own section further down the same page. What the
    cut saved was five lines. The box scrolls instead.

    Nested divs rather than a nested list. Mintlify's prose styles own ``li`` —
    its own bullet, its own padding, its own vertical rhythm — and a tree drawn
    with lists spends its life outbidding them.
    """
    drawn: Set[type] = set()

    def node(model: type) -> str:
        label = link_html(ctx, model.__name__, ctx.homes.get(model))
        children = [c for c in direct_children(model) if c in published]
        if model in drawn:
            # Marking it only when there is a subtree elsewhere: on a model with
            # no children, a leaf here and a leaf there say the same thing.
            note = ' <span className="tree-note">above</span>' if children else ""
            return f'<div className="tree-node">{label}{note}</div>'
        drawn.add(model)
        if not children:
            return f'<div className="tree-node">{label}</div>'
        inner = "".join(node(child) for child in children)
        return (
            f'<div className="tree-node">{label}'
            f'<div className="tree-children">{inner}</div>'
            f"</div>"
        )

    items = "".join(node(root) for root in roots)
    # The scroller is a child rather than the box itself, so the copy button
    # that model-tree.js hangs in the corner stays put while the tree scrolls.
    return (
        '<div className="model-tree">'
        f'<div className="model-tree-scroll">{items}</div>'
        "</div>"
    )


