def all_pages() -> Dict[str, str]:
    pages: Dict[str, str] = {}
    for pack in PACKS:
        pages.update(pack_pages(pack))
    return pages


def _generated_paths() -> List[Path]:
    """Every file previously written here, so a removed tool's page goes away."""
    out = []
    for path in PACK_DOCS.rglob("*.mdx"):
        if path.parent != PACK_DOCS and _BANNER in path.read_text():
            out.append(path)
    return out


def main(argv: Sequence[str]) -> int:
    check = "--check" in argv
    pages = all_pages()
    config = render_docs_json()

    wanted = {DOCS / path: body for path, body in pages.items()}
    stale: List[str] = []

    for path in _generated_paths():
        if path not in wanted:
            stale.append(f"{path.relative_to(DOCS)} (removed)")
            if not check:
                path.unlink()

    for path, body in sorted(wanted.items()):
        current = path.read_text() if path.exists() else None
        if current == body:
            continue
        stale.append(str(path.relative_to(DOCS)))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body)

    docs_json = DOCS / "docs.json"
    if docs_json.read_text() != config:
        stale.append("docs.json")
        if not check:
            docs_json.write_text(config)

    if not check:
        for pack in PACKS:
            legacy = PACK_DOCS / f"{pack}.openapi.json"
            if legacy.exists():
                legacy.unlink()

    if check and stale:
        print(f"stale pack reference: {', '.join(stale[:8])}", file=sys.stderr)
        print(f"run: uv run python {_SCRIPT}", file=sys.stderr)
        return 1

    verb = "stale" if check else "rewritten"
    print(f"{len(pages)} pack reference pages checked, {len(stale)} {verb}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
