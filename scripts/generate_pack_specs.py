#!/usr/bin/env python
"""Regenerate the per-tool reference under ``docs/packs/<pack>/``.

``generate_pack_docs.py`` writes the pack *page* — the prose, the wire table,
the list of tool names. This writes the layer under it: for every tool, each
argument it accepts with the description the tool publishes and the constraints
that survived, and for every object and enum those arguments reach, one table
naming its fields. The description is the provider's own text plus any ``Gloss``
the pack declares, because it is read from the schema the model receives.

Three things shape the output, and each of them is a decision worth stating.

**Tables, not a schema explorer.** An argument list is a table — name, type,
description — and a reader comparing two tools reads two tables faster than
they open two trees of disclosure triangles. The type is a link, so the table
stays three columns wide however deep the model goes.

**One page per category, not per object.** ``Event`` alone pulls fifteen nested
models; a pack that covered all of Google Calendar would run to some hundreds.
Hundreds of sidebar entries is not navigation, and hundreds of page loads to
read one model is not reading. So every object and enum a category uses lands
on that category's ``objects`` page as an anchored section, and a type link is
a jump within the page a reader is already on.

**The category is derived, never declared.** A tool's category is the module
its request model is declared in: ``EventsListRequest`` lives in
``charter.packs.gcalendar.types.event.actions``, so it is an ``event`` tool.
Packs were already organised that way, which is the point — a declared list
beside ``TOOLS`` is a second place to update and therefore a place to drift.
A pack that keeps its types in one module gets one category, and the level is
dropped rather than rendered as a group of one.

Enums are named the same way. Pydantic inlines a ``Literal`` alias, so the name
the author chose is gone by the time the schema is built. It is recovered by
scanning the pack's type modules for module-level ``Literal`` bindings and
matching on the values. That makes it the author's call: name a ``Literal`` at
module level and it earns a section, an anchor and a link from every field that
uses it; leave it inline and it renders inline, which for two values is what it
deserves.

Usage::

    uv run python scripts/generate_pack_specs.py            # rewrite the pages
    uv run python scripts/generate_pack_specs.py --check    # exit 1 if stale
"""

