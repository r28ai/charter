def _is_oneof(model: type) -> bool:
    """Whether a repeated model is a union of alternatives rather than a resource.

    `Sheet` and `Request` are both repeated models with fifteen-plus optional
    fields, and only one of them is a set of mutually exclusive choices. The
    difference is declared: a oneof carries the validator enforcing exactly one,
    so a `keep` example is only generated where keeping a subset means anything.
    """
    fields = model.model_fields
    if len(fields) < 10 or any(f.is_required() for f in fields.values()):
        return False
    return bool(model.__pydantic_decorators__.model_validators)


def _widest_union(tool: Tool) -> Optional[Tuple[str, int, List[str]]]:
    """The oneof a wide tool hides, as (field path, member count, first members).

    A batch endpoint puts every edit it supports behind one repeated field, and
    that field is what a reader narrows. Found rather than declared, so a pack
    that grows a union gets the right example without anyone editing this file.
    """
    best: Optional[Tuple[str, int, List[str]]] = None

    def consider(path: str, annotation: Any) -> None:
        nonlocal best
        item = _list_item_model(annotation)
        if item is None or not _is_oneof(item):
            return
        members = list(item.model_fields)
        if best is None or len(members) > best[1]:
            best = (path, len(members), members[:3])

    for name, field in tool.args_schema.model_fields.items():
        consider(name, field.annotation)
        # Docs wraps its union one level down, in `body.requests`. A top-level
        # scan finds Sheets' and misses the pack the feature was built for.
        nested = _model_of(field.annotation)
        if nested is not None:
            for sub, sub_field in nested.model_fields.items():
                consider(f"{name}.{sub}", sub_field.annotation)
    return best


def _peel(annotation: Any) -> Any:
    """``Optional[List[X]]`` -> ``X``, however the two are nested.

    Both orders occur, and handling only the outer one is how `sheets`, the
    `Optional[List[Sheet]]` holding most of a spreadsheet, went unseen.
    """
    args = get_args(annotation)
    origin = get_origin(annotation)
    if origin is not None and args:
        real = [a for a in args if a is not type(None)]
        if real and (origin is list or len(real) == 1):
            return _peel(real[0])
    return annotation


def _model_of(annotation: Any) -> Optional[type]:
    """The BaseModel a field is built from, through Optional and List."""
    peeled = _peel(annotation)
    return peeled if isinstance(peeled, type) and issubclass(peeled, BaseModel) else None


def _list_item_model(annotation: Any) -> Optional[type]:
    """The BaseModel a repeated field repeats, or None if it is not repeated."""
    inner = annotation
    if get_origin(inner) is not list:
        real = [a for a in get_args(inner) if a is not type(None)]
        inner = real[0] if len(real) == 1 else inner
    if get_origin(inner) is not list:
        return None
    return _model_of(inner)


def _heaviest_optional_branches(tool: Tool, limit: int = 3) -> List[str]:
    """The optional sub-objects costing the most, as dotted paths, largest first.

    A resource with no union is wide because of its branches. Those branches are
    rarely at the top: ``events_insert`` takes a required ``event``, and the
    weight is the fifteen models hanging off it. So this looks one level inside
    each top-level model too, and returns what ``drop`` would be given.

    Sized by their own rendered schema, so the example names the expensive branch
    rather than the first one declared.
    """
    sized: List[Tuple[int, str]] = []

    def consider(path: str, field: Any) -> None:
        if field.is_required():
            return
        model = _model_of(field.annotation)
        if model is not None:
            sized.append((len(json.dumps(model.model_json_schema())), path))

    for name, field in tool.args_schema.model_fields.items():
        consider(name, field)
        nested = _model_of(field.annotation)
        if nested is not None:
            for sub, sub_field in nested.model_fields.items():
                consider(f"{name}.{sub}", sub_field)

    sized.sort(reverse=True)
    ordered = [path for _, path in sized]
    leafward = [p for p in ordered if not any(q.startswith(f"{p}.") for q in ordered)]
    return leafward[:limit]


def _unique(tool: Tool, name: str) -> bool:
    """Whether a bare field name resolves to one path on this tool."""
    every = tool.paths(depth=None)
    return sum(1 for p in every if p == name or p.endswith(f".{name}")) == 1


def wide_schema_note(tool: Tool) -> Optional[str]:
    """What to do about a tool whose schema is larger than the task.

    Rendered from the measured size, so it appears exactly where it is true and
    disappears if the schema shrinks.
    """
    size = len(json.dumps(tool.to_json_schema()))
    if size < _WIDE_SCHEMA_BYTES:
        return None

    union = _widest_union(tool)
    if union is not None:
        path, count, sample = union
        why = f"because `{path}` carries {count} kinds of edit behind one method"
        names = [m if _unique(tool, m) else f"{path}.{m}" for m in sample]
        selector = "keep={" + ", ".join(f'"{m}"' for m in names) + "}"
        closing = f"Three of the {count} are kept here. Which ones your agent needs is yours to pick."
    else:
        why = "because it models the whole resource this endpoint writes"
        heavy = _heaviest_optional_branches(tool)
        if not heavy:
            return None
        selector = "drop={" + ", ".join(f'"{m}"' for m in heavy) + "}"
        closing = "Those are its heaviest branches by schema size, not a recommendation: which ones you can spare is yours to decide."

    return "\n".join(
        [
            "<Warning>",
            f"  This tool's JSON schema is {size // 1024} KB, {why}.",
            "  That is more context than most tasks. Narrow it at the call site",
            "  with [`Tool.derived`](/reference/tool#tool-derived):",
            "",
            "  ```python",
            f"  narrowed = {tool.pack}.{tool.name}.derived(",
            f'      name="{tool.name}_narrowed",',
            f"      {selector},",
            "  )",
            "  ```",
            "",
            f"  {closing} The tool underneath is unchanged.",
            "  See [Projections](/tools/projections).",
            "</Warning>",
        ]
    )


def _frontmatter_value(text: str) -> str:
    """One line of YAML, safe to sit inside double quotes.

    A tool description is prose written by a pack author, and a quotation mark
    in it — naming a literal argument such as ``mode="external_url"`` — closes
    the YAML string early and fails the whole docs build rather than that one
    page. Escaped here rather than banned there: the alternative is a rule about
    punctuation that nothing enforces until a release is cut.
    """
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def tool_page(ctx: Context, pack: str, tool: Tool, shared_route: Optional[str]) -> str:
    schema = tool.to_json_schema()["parameters"]
    properties: Dict[str, Any] = schema.get("properties", {})
    required = set(schema.get("required", []))
    placement = _placements(tool)
    pills = marker_map(tool.args_schema).get(tool.args_schema, {})

    base = tool.base_url
    server = "" if callable(base) else str(base).rstrip("/")
    route = f"{server}{route_of(tool)}"

    parts = [
        "---",
        f'title: "{tool.name}"',
        f'description: "{_frontmatter_value(tool.description)}"',
        # The pill beside the name in the sidebar. Mintlify drew it from the
        # OpenAPI operation before the reference moved to MDX, and a sidebar
        # that stopped saying which of four `issues_*` tools writes would be a
        # worse page list than the one it replaced.
        f'tag: "{tool.method}"',
        "---",
        "",
        _BANNER,
        "",
        f'<div className="tool-route">'
        f'<span className="tool-row-method" data-method="{tool.method}">{tool.method}</span>'
        f"<code>{jsx_string(route)}</code>"
        f"</div>",
        "",
        code_sample(pack, tool),
        "",
    ]

    note = preamble(tool, shared_route)
    if note:
        parts += [note, ""]

    wide = wide_schema_note(tool)
    if wide:
        parts += [wide, ""]

    grouped: Dict[str, Dict[str, Any]] = {"path": {}, "query": {}, "body": {}}
    for name, node in properties.items():
        grouped[placement.get(name, "body")][name] = node

    for key, heading in _SECTIONS:
        if not grouped[key]:
            continue
        parts += [f"## {heading}", "", table(field_rows(ctx, grouped[key], required, pills)), ""]

    if not any(grouped.values()):
        parts += ["This tool takes no arguments.", ""]

    return "\n".join(parts).rstrip() + "\n"


