def code_sample(pack: str, tool: Tool) -> str:
    """The call a reader should copy, which is never curl.

    Required arguments are named and left as ellipses. A sample that invented
    plausible values would be a sample somebody pastes.

    Titled with a filename, as every block on the pack pages is. Mintlify falls
    back to the language when there is no title, and a header reading "Python"
    on a page inside a Python SDK's reference spends a line saying nothing.
    """
    required = tool.to_json_schema()["parameters"].get("required", [])
    args = ", ".join(f'"{name}": ...' for name in required)
    return (
        f"```python {pack}_{tool.name}.py\n"
        f"from charter.packs import {pack}\n\n"
        f"result = await {pack}.{tool.name}.ainvoke({{{args}}})\n"
        "```"
    )


def route_of(tool: Tool) -> str:
    """The tool's URL template, with placeholders spelled as the arguments are.

    ``gcalendar`` writes ``calendars/{calendar_id}/events`` while ``gmail``
    writes ``{userId}``; the LLM schema serialises both as camelCase. The
    template is normalised rather than the argument renamed — the page is an
    argument reference, and one snake_case name among camelCase ones reads as a
    different parameter. The wire's own spelling stays on the pack page's wire
    table.
    """
    normalised = re.sub(r"\{(\w+)\}", lambda m: "{" + to_camel(m.group(1)) + "}", tool.url_template)
    return "/" + normalised.lstrip("/")


def _placements(tool: Tool) -> Dict[str, str]:
    """Where each top-level argument goes, read off the wire schema's markers."""
    from charter.types.markers import Body, Query
    from charter.types.markers import Path as PathMarker

    out: Dict[str, str] = {}
    for name, field in tool.args_schema.model_fields.items():
        for marker in field.metadata:
            if isinstance(marker, PathMarker):
                out[to_camel(name)] = "path"
            elif isinstance(marker, Query):
                out[to_camel(name)] = "query"
            elif isinstance(marker, Body):
                out[to_camel(name)] = "body"
    return out


def preamble(tool: Tool, shared_route: Optional[str] = None) -> Optional[str]:
    """What the tool declares that no argument list can show.

    Scopes and pagination are properties of the endpoint rather than of any one
    field, and both change what a caller has to do — ask for the right grant,
    walk the cursor. Rendered above the arguments, from the declaration.
    """
    notes: List[str] = []
    if shared_route:
        notes.append(
            f"Posts a GraphQL document to `{tool.method} {shared_route}`, "
            "as every tool in this pack does."
        )
    if tool.scopes:
        notes.append("Requires " + ", ".join(f"`{scope}`" for scope in tool.scopes) + ".")
    if tool.pagination is not None:
        pagination = tool.pagination
        if pagination.page_param:
            notes.append(
                f"Pages by number: `{pagination.page_param}` with `{pagination.per_page_param}`."
            )
        else:
            notes.append(
                f"Pages by cursor: `{pagination.cursor_field}` is sent back as "
                f"`{pagination.cursor_param}`."
            )
    if tool.quota_cost is not None:
        notes.append(f"Costs {tool.quota_cost} against the provider's own quota.")
    if not notes:
        return None
    return "<Note>\n  " + " ".join(notes) + "\n</Note>"


