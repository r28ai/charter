def _shared_route(tools: Sequence[Tool]) -> Optional[str]:
    """The one endpoint a GraphQL pack posts every tool to, if there is one."""
    routes = {(tool.method, route_of(tool)) for tool in tools}
    if len(routes) == 1 and len(tools) > 1:
        return next(iter(routes))[1]
    return None


def _defs_for(tools: Sequence[Tool]) -> Dict[str, Dict[str, Any]]:
    """Every ``$defs`` entry the pack's tools produce, merged by name.

    Two tools deriving the same wire model do **not** always produce the same
    view of it. Linear narrows a filter differently depending on where it sits:
    ``IssueFilter`` reached as an argument keeps forty-one conditions, and the
    same type reached as a relation - ``DocumentFilter.issue`` - keeps the three
    that identify an issue. Both are correct, and the reference documents the
    type once, so it documents the widest view: every narrower one is a subset of
    it, and a field that links to the type from a narrow context still finds
    every field it can name.

    Firecrawl's ``Format`` and friends are genuinely different classes that share
    a name. Those are keyed by class below; this map is only consulted through
    ``Context.models``, which is.
    """
    out: Dict[str, Dict[str, Any]] = {}
    for tool in tools:
        for name, body in tool.to_json_schema()["parameters"].get("$defs", {}).items():
            existing = out.get(name)
            if existing is None or len(body.get("properties") or {}) > len(
                existing.get("properties") or {}
            ):
                out[name] = body
    return out


def pack_pages(pack: str) -> Dict[str, str]:
    """Every page one pack publishes, as ``{path relative to docs/: body}``.

    A model is published on the first category page whose tools reach it, and
    linked from every other. Two rules follow from that and are worth stating,
    because the obvious alternative fails on a real pack:

    Home by *use*, not by where the model is declared. A model homed on the page
    of the module that declares it can land on a page whose tools never build
    its schema — gdocs keeps every type in one module and renders flat — and
    then there is a link with no table under it.

    Publish only what the LLM view emits. ``model_tree`` walks the wire model,
    which still carries the ``response_only`` fields the view drops; Google
    Calendar's ``Creator`` is one of them. Those are types no caller can set, so
    they get no section, and nothing may link to them either.
    """
    module = pack_module(pack)
    tools: List[Tool] = list(module.TOOLS)
    groups = categorised(pack, tools)
    shared = _shared_route(tools)
    enums = named_enums(pack)

    homes: Dict[type, Optional[str]] = {}
    published: Dict[Optional[str], List[type]] = {}
    # ``$defs`` name -> wire model, per category. Two classes in one pack can
    # share a name — firecrawl's ``search`` and ``scrape`` each declare a
    # ``Format`` — so a pack-wide map would resolve one page's refs to the
    # other page's model.
    def_names: Dict[Optional[str], Dict[str, type]] = {}

    for slug, category_tools in groups:
        names: Dict[str, type] = {}
        mine: List[type] = []
        for tool in category_tools:
            defs = tool.to_json_schema()["parameters"].get("$defs", {})
            emitted = {name.removesuffix(_LLM_SUFFIX): name for name in defs}
            for model in model_tree(tool.args_schema):
                if model is tool.args_schema:
                    continue
                key = emitted.get(model.__name__)
                if key is None:
                    continue
                names.setdefault(key, model)
                if model not in homes:
                    homes[model] = slug
                    mine.append(model)
        def_names[slug] = names
        published[slug] = mine

    pills: Dict[type, Dict[str, List[Tuple[str, str]]]] = {}
    for tool in tools:
        pills.update(marker_map(tool.args_schema))

    enum_homes: Dict[Tuple[str, ...], Optional[str]] = {}
    contexts: Dict[Optional[str], Context] = {}
    pages: Dict[str, str] = {}

    for slug, category_tools in groups:
        ctx = Context(
            pack=pack,
            category=slug,
            enums=enums,
            enum_homes=enum_homes,
            models=def_names[slug],
            homes=homes,
        )
        contexts[slug] = ctx
        directory = f"packs/{pack}/{slug}" if slug else f"packs/{pack}"
        for tool in category_tools:
            pages[f"{directory}/{tool.name}.mdx"] = tool_page(ctx, pack, tool, shared)

    for slug, category_tools in groups:
        ctx = contexts[slug]
        # From here the objects page is what is being written, so a link to a
        # heading on it is an anchor rather than a round trip through the router.
        ctx.page = objects_page(pack, slug)
        directory = f"packs/{pack}/{slug}" if slug else f"packs/{pack}"
        models = published[slug]

        roots: List[type] = []
        for tool in category_tools:
            for child in direct_children(tool.args_schema):
                if child not in roots and child in set(models):
                    roots.append(child)

        body = objects_mdx(
            ctx,
            category_title(pack, slug) if slug else _pack_title(pack),
            roots,
            models,
            list(enums.values()),
            _defs_for(category_tools),
            pills,
        )
        if body:
            pages[f"{directory}/objects.mdx"] = body

    return pages


