"""Request schemas for the GitHub pack.

One module per area of the API, named the way GitHub names it: ``issues``,
``pulls``, ``repos``, ``git`` (the object store), ``checks``, ``actions``,
``releases``, ``monitoring`` (notifications and security alerts), ``search``
and ``users``, over the two shared pieces in ``common``.

The split is what the reference documentation is generated from — each module
becomes a section — so a schema lands in the module whose endpoint it belongs
to, not the one whose imports are most convenient.
"""

